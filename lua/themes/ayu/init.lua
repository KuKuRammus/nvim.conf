-- Loader and compiler.
--
--   require("<mod>").load()     apply the theme (recompiles first if any theme file changed)
--   require("<mod>").compile()  rebuild the cache now and re-apply if ayu is active
--   require("<mod>.palette")    the color table, for use in your own config (statusline etc.)
-- <mod> is the path of this folder under lua/, e.g. "themes.ayu" for lua/themes/ayu/.
--
-- Compiling runs every file in groups/ against the palette and writes a single Lua file
-- of nvim_set_hl() calls to stdpath("cache")/ayu/ayu.lua. Loading just runs that file.

local M = {}

-- Module name this file was required as ("ayu", "themes.ayu", ...), so the theme
-- works from any folder under lua/.
local mod = ... or "ayu"
local src = debug.getinfo(1, "S").source:sub(2):match("^(.*)/init%.lua$")
local cache_dir = vim.fn.stdpath("cache") .. "/ayu"
M.cache_file = cache_dir .. "/ayu.lua"

local function mtime(path)
    local st = vim.uv.fs_stat(path)
    return st and (st.mtime.sec + st.mtime.nsec * 1e-9) or 0
end

-- Every file and directory under lua/ayu (directories catch added/removed files).
local function sources()
    local list = { src }
    for name in vim.fs.dir(src, { depth = 10 }) do
        list[#list + 1] = src .. "/" .. name
    end
    return list
end

-- Group modules as require() names, sorted so output is deterministic.
local function group_modules()
    local mods = {}
    for name, kind in vim.fs.dir(src .. "/groups", { depth = 10 }) do
        if kind == "file" and name:match("%.lua$") then
            mods[#mods + 1] = mod .. ".groups." .. name:gsub("%.lua$", ""):gsub("/", ".")
        end
    end
    table.sort(mods)
    return mods
end

local function serialize(spec)
    local keys = vim.tbl_keys(spec)
    table.sort(keys)
    local parts = {}
    for _, k in ipairs(keys) do
        local v = spec[k]
        parts[#parts + 1] = ("%s = %s"):format(k, type(v) == "string" and ("%q"):format(v) or tostring(v))
    end
    return "{ " .. table.concat(parts, ", ") .. " }"
end

local function is_stale()
    local cached = mtime(M.cache_file)
    if cached == 0 then
        return true
    end
    for _, path in ipairs(sources()) do
        if mtime(path) > cached then
            return true
        end
    end
    return false
end

function M.compile()
    -- Drop cached modules so edits made in this session are picked up.
    local groups_prefix = mod .. ".groups."
    for name in pairs(package.loaded) do
        if name == mod .. ".palette" or name:sub(1, #groups_prefix) == groups_prefix then
            package.loaded[name] = nil
        end
    end

    local c = require(mod .. ".palette")
    local groups, origin = {}, {}
    for _, group_mod in ipairs(group_modules()) do
        for name, spec in pairs(require(group_mod)(c)) do
            if origin[name] then
                error(("ayu: %s is defined in both %s and %s"):format(name, origin[name], group_mod))
            end
            groups[name], origin[name] = spec, group_mod
        end
    end

    local names = vim.tbl_keys(groups)
    table.sort(names)

    local out = {
        "-- Generated by ayu.compile(); edit the files in lua/ayu/ instead.",
        'vim.cmd("highlight clear")',
        'vim.o.background = "dark"',
        'vim.g.colors_name = "ayu"',
        "local h = vim.api.nvim_set_hl",
    }
    for _, name in ipairs(names) do
        out[#out + 1] = ("h(0, %q, %s)"):format(name, serialize(groups[name]))
    end
    for i, color in ipairs(c.term) do
        out[#out + 1] = ("vim.g.terminal_color_%d = %q"):format(i - 1, color)
    end

    vim.fn.mkdir(cache_dir, "p")
    local f = assert(io.open(M.cache_file, "w"))
    f:write(table.concat(out, "\n"), "\n")
    f:close()

    if vim.g.colors_name == "ayu" then
        dofile(M.cache_file)
    end
    return M.cache_file, #names
end

function M.load()
    if is_stale() then
        -- A broken edit shouldn't leave you without colors: report it, keep the last good cache.
        local ok, err = pcall(M.compile)
        if not ok and mtime(M.cache_file) > 0 then
            vim.schedule(function()
                vim.notify(tostring(err), vim.log.levels.ERROR)
            end)
        elseif not ok then
            error(err, 0)
        end
    end
    local ok = pcall(dofile, M.cache_file)
    if not ok then -- corrupt or outdated cache: rebuild once
        M.compile()
        dofile(M.cache_file)
    end
end

return M
